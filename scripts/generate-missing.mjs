// Render docs/MISSING.md from parity/inventory.json (scripts/inventory.mjs): per editor state,
// what the oracle shows that our editor does not, untracked gaps first. Never edit the output.
import { readFileSync, writeFileSync } from 'node:fs';

const inv = JSON.parse(readFileSync(new URL('../parity/inventory.json', import.meta.url), 'utf8'));
const visual = (() => { try { return JSON.parse(readFileSync(new URL('../parity/visual.json', import.meta.url), 'utf8')); } catch { return null; } })();
const pct = (name) => { const v = visual?.states.find((x) => x.name === name); return v ? `${v.percent}%` : ''; };
const ORDER = ['UNTRACKED', 'mentioned', 'side panel only', 'tracked', 'out of scope'];
const MEANING = {
  UNTRACKED: 'no item lists or mentions it: a gap nobody wrote down',
  mentioned: 'an item\'s text names it but does not list it in `controls`: check and list it',
  'side panel only': 'ours has it in the side panel, the oracle has it on the canvas',
  tracked: 'an item lists it in `controls`',
  'out of scope': 'docs/decisions/0005',
};
const count = (s, st) => s.missing.filter((m) => m.status === st).length;
const cell = (t) => String(t).replace(/\|/g, '\\|');
const lines = [
  '# What the oracle shows that ours does not',
  '',
  `Generated by \`npm run missing\` from \`parity/inventory.json\` (\`scripts/inventory.mjs\`, captured ${inv.capturedAt}). Never edit by hand.`,
  '',
  'For each editor state, the inventory lists every visible control and label of the editor on the oracle and on ours, and keeps what ours lacks. Each gap is matched against `parity/items.json`:',
  '',
  ...ORDER.map((st) => `- **${st}**: ${MEANING[st]}.`),
  '',
  '## By state',
  '',
  '| State | What | Oracle labels | Ours has | Untracked | Mentioned | Side panel only | Tracked | Canvas pixels differing |',
  '|---|---|---|---|---|---|---|---|---|',
  ...inv.states.map((s) => `| ${s.name} | ${cell(s.what)} | ${s.oracle} | ${s.present} | ${count(s, 'UNTRACKED')} | ${count(s, 'mentioned')} | ${count(s, 'side panel only')} | ${count(s, 'tracked')} | ${pct(s.name)} |`),
  '',
];
for (const st of ORDER) {
  const rows = inv.states.flatMap((s) => s.missing.filter((m) => m.status === st).map((m) => ({ ...m, state: s.name })));
  if (!rows.length) continue;
  // One row per label, with every state it appears in.
  const by = new Map();
  for (const r of rows) {
    const k = r.label.toLowerCase();
    if (!by.has(k)) by.set(k, { ...r, states: [] });
    by.get(k).states.push(r.state);
  }
  lines.push(`## ${st[0].toUpperCase()}${st.slice(1)} (${by.size})`, '', '| Label | Kind | States | Items |', '|---|---|---|---|');
  for (const r of by.values()) lines.push(`| ${cell(r.label)} | ${r.kind === 'control' ? r.role : 'text'} | ${r.states.join(', ')} | ${[...r.items, ...r.outOfScope].join(', ')} |`);
  lines.push('');
}
const errors = inv.states.filter((s) => s.error);
if (errors.length) lines.push('## States that did not run cleanly', '', ...errors.map((s) => `- ${s.name}: ${s.error}`), '');
writeFileSync(new URL('../docs/MISSING.md', import.meta.url), lines.join('\n'));
console.log(`wrote docs/MISSING.md: ${inv.states.length} states`);
