// Draws docs/images/parity.svg and writes docs/PARITY.md from parity/items.json.
// One cell per item: done, partial, open or unknown. Never edit the outputs by hand.
import { items, milestones, esc, writeIfChanged, STYLE } from './lib/board.mjs';

const SVG = new URL('../docs/images/parity.svg', import.meta.url);
const MD = new URL('../docs/PARITY.md', import.meta.url);
const W = 1200, PAD = 40, ROW = 46, TOP = 214, LABEL = 300, CELL = 50, CGAP = 6, CH = 30;
const ORDER = ['done', 'partial', 'open', 'unknown'];
const NAME = { done: 'done', partial: 'partial', open: 'open', unknown: 'unknown' };
const MARK = { done: '✓', partial: '◐', open: '○', unknown: '?' };

function groups(all) {
  const map = new Map();
  for (const it of all) {
    if (!map.has(it.area)) map.set(it.area, []);
    map.get(it.area).push(it);
  }
  return [...map];
}

const count = (list) => Object.fromEntries(ORDER.map((s) => [s, list.filter((i) => i.status === s).length]));

export function svg(all) {
  const rows = groups(all);
  const c = count(all);
  const H = TOP + rows.length * ROW + 56;
  const barW = W - 2 * PAD;
  const out = [];
  out.push(`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" role="img" aria-labelledby="t d">`);
  out.push(`<title id="t">Fluid editor parity</title>`);
  out.push(`<desc id="d">${c.done} of ${all.length} items done, ${c.partial} partial, ${c.open} open, ${c.unknown} unknown. ${esc(rows.map(([a, l]) => `${a}: ${count(l).done} of ${l.length} done`).join('. '))}.</desc>`);
  out.push(STYLE.replace('</style>', `  .c-done { fill: var(--done); } .t-done { fill: #fff; }
  .c-partial { fill: var(--partbg); stroke: var(--now); } .t-partial { fill: var(--now); }
  .c-open { fill: var(--card); stroke: var(--line); } .t-open { fill: var(--muted); }
  .c-unknown { fill: url(#hatch); stroke: var(--unk); stroke-dasharray: 3 2; } .t-unknown { fill: var(--unk); }
  .hatch-bg { fill: var(--card); } .hatch-line { stroke: var(--line); }
  .s-done { fill: var(--done); } .s-partial { fill: var(--now); } .s-open { fill: var(--line); } .s-unknown { fill: var(--unk); }
</style>`));
  out.push(`<defs><pattern id="hatch" width="6" height="6" patternUnits="userSpaceOnUse" patternTransform="rotate(45)"><rect width="6" height="6" class="hatch-bg"/><path d="M0 0V6" class="hatch-line" stroke-width="3"/></pattern></defs>`);
  out.push(`<rect class="bg" width="${W}" height="${H}" rx="16"/>`);
  out.push(`<text x="${PAD}" y="70" font-size="36" font-weight="700" letter-spacing="-0.8">Parity</text>`);
  out.push(`<text x="${PAD}" y="102" font-size="19" class="muted">Everything that has to match Fluid Engine, one cell per item.</text>`);
  out.push(`<text x="${W - PAD}" y="70" font-size="40" font-weight="700" text-anchor="end">${c.done}<tspan class="muted" font-weight="400"> / ${all.length}</tspan></text>`);
  out.push(`<text x="${W - PAD}" y="102" font-size="16" text-anchor="end" class="muted">items done</text>`);
  let x = PAD;
  for (const s of ORDER) {
    const w = (barW * c[s]) / all.length;
    if (w) out.push(`<rect x="${x}" y="124" width="${w}" height="10" class="s-${s}"/>`);
    x += w;
  }
  out.push(`<text x="${PAD}" y="172" font-size="16">${ORDER.map((s, i) => `<tspan class="${{ done: 'done', partial: 'now', open: 'todo', unknown: 'unk' }[s]}"${i ? ' dx="24"' : ''}>${MARK[s]} ${c[s]} ${NAME[s]}</tspan>`).join('')}</text>`);
  out.push(`<text x="${W - PAD}" y="172" font-size="16" text-anchor="end" class="muted">unknown: needs a trace on the oracle before it can be built</text>`);
  out.push(`<path d="M${PAD} 190H${W - PAD}" class="rule"/>`);
  rows.forEach(([area, list], r) => {
    const y = TOP + r * ROW;
    const k = count(list);
    out.push(`<g data-area="${esc(area)}">`);
    out.push(`<text x="${PAD}" y="${y + 20}" font-size="15" font-weight="600">${esc(area)}</text>`);
    out.push(`<text x="${PAD + LABEL - 16}" y="${y + 20}" font-size="14" text-anchor="end" class="${k.done === list.length ? 'done' : 'muted'}">${k.done}/${list.length}</text>`);
    list.forEach((it, i) => {
      const cx = PAD + LABEL + i * (CELL + CGAP);
      out.push(`<rect x="${cx}" y="${y}" width="${CELL}" height="${CH}" rx="6" class="c-${it.status}"><title>${esc(`${it.id} ${it.title}: ${it.status}`)}</title></rect>`);
      out.push(`<text x="${cx + CELL / 2}" y="${y + 20}" font-size="13" font-weight="700" text-anchor="middle" class="t-${it.status}">${it.id}</text>`);
    });
    out.push(`</g>`);
  });
  out.push(`<text x="${PAD}" y="${H - 26}" font-size="14" class="muted">Generated by scripts/generate-parity.mjs from parity/items.json · the list with evidence: docs/PARITY.md</text>`);
  out.push(`</svg>\n`);
  return out.join('\n');
}

export function md(all, ms) {
  const c = count(all);
  const name = Object.fromEntries(ms.map((m) => [m.id, m.name]));
  const lines = [
    '# Parity',
    '',
    '[![Parity: one cell per item, done, partial, open or unknown](images/parity.svg)](../README.md)',
    '',
    `${c.done} of ${all.length} items done, ${c.partial} partial, ${c.open} open, ${c.unknown} unknown.`,
    'Generated from [`parity/items.json`](../parity/items.json) by `npm run parity`. Edit the JSON, never this page.',
    '',
  ];
  for (const [area, list] of groups(all)) {
    lines.push(`## ${area}`, '', '| Id | Item | Milestone | Status | Gate or evidence |', '|---|---|---|---|---|');
    for (const it of list) {
      const proof = [it.gate && `Gate: ${it.gate}`, it.evidence && `Evidence: ${it.evidence}`, it.outOfScope?.length && `Out of scope (docs/decisions): ${it.outOfScope.join('; ')}`].filter(Boolean).join('. ');
      lines.push(`| ${it.id} | ${it.title.replace(/\|/g, '\\|')} | ${it.milestone} ${name[it.milestone] || ''} | ${MARK[it.status]} ${it.status} | ${proof.replace(/\|/g, '\\|')} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

const all = items();
writeIfChanged(SVG, svg(all), 'docs/images/parity.svg');
writeIfChanged(MD, md(all, milestones()), 'docs/PARITY.md');
