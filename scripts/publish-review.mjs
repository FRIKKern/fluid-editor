// Publish the gap review to Barkpark: for each state in parity/inventory.json, the oracle and
// our screenshots (uploaded to the Barkpark media library) and what ours lacks, untracked
// first. The screenshots stay out of the repo (O2); they live in the private workspace.
// Usage: node scripts/publish-review.mjs --shots <dir> [--slug fluid-editor-gap-review-YYYY-MM-DD]
// Needs `bp` and ~/.config/barkpark/config.json (server and token of the gyl workspace).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const arg = (n, d) => (args.includes(`--${n}`) ? args[args.indexOf(`--${n}`) + 1] : d);
const shots = arg('shots');
if (!shots) throw new Error('--shots <dir> is required (the folder scripts/inventory.mjs wrote)');
const inv = JSON.parse(readFileSync(new URL('../parity/inventory.json', import.meta.url), 'utf8'));
const slug = arg('slug', `fluid-editor-gap-review-${inv.capturedAt}`);
const cfg = JSON.parse(readFileSync(`${process.env.HOME}/.config/barkpark/config.json`, 'utf8'));
const server = cfg.server;

async function upload(file) {
  const form = new FormData();
  form.append('file', new Blob([readFileSync(file)], { type: 'image/png' }), file.split('/').pop());
  const res = await fetch(`${server}/media/upload?dataset=${cfg.dataset || 'production'}`, { method: 'POST', headers: { Authorization: `Bearer ${cfg.token}` }, body: form });
  if (!res.ok) throw new Error(`upload ${file}: ${res.status}`);
  const j = await res.json();
  return server + j.url;
}

const t = (value) => ({ type: 'text', value: String(value) });
const p = (id, value) => ({ id, type: 'paragraph', content: [t(value)] });
const h = (id, level, text) => ({ id, type: 'heading', level, text });
const table = (id, head, rows) => ({ id, type: 'table', head: head.map((x) => [t(x)]), rows: rows.map((r) => r.map((x) => [t(x)])) });
const fig = (id, src, alt, caption) => ({ id, type: 'figure', child: { type: 'image', src, alt }, caption: [t(caption)] });

const visual = (() => { try { return JSON.parse(readFileSync(new URL('../parity/visual.json', import.meta.url), 'utf8')); } catch { return null; } })();
const ORDER = ['UNTRACKED', 'mentioned', 'side panel only', 'tracked', 'out of scope'];
const n = (s, st) => s.missing.filter((m) => m.status === st).length;
const all = inv.states.flatMap((s) => s.missing);
const uniq = (st) => new Set(all.filter((m) => m.status === st).map((m) => m.label.toLowerCase())).size;
let k = 0;
const id = () => `b${++k}`;
const blocks = [
  { id: id(), type: 'eyebrow', text: `Fluid editor · gap review · ${inv.capturedAt}` },
  h(id(), 1, 'What the oracle shows that ours does not'),
  { id: id(), type: 'ingress', content: [t(`${inv.states.length} editor states, driven the same way on the trial site and on our editor. ${uniq('UNTRACKED')} labels the oracle shows are missing from ours and written down nowhere. ${uniq('mentioned')} more are named in an item but not listed as covered, and ${uniq('side panel only')} exist in ours only in the side panel.`)] },
  p(id(), 'Each state shows the oracle first, then ours, then what ours lacks. Untracked means no item in parity/items.json lists or names it. The list is generated by scripts/inventory.mjs; the repo keeps the same list in docs/MISSING.md.'),
  table(id(), ['State', 'Oracle labels', 'Ours has', 'Untracked', 'Mentioned', 'Side panel only', 'Canvas pixels differing'], inv.states.map((s) => [s.name, s.oracle, s.present, n(s, 'UNTRACKED'), n(s, 'mentioned'), n(s, 'side panel only'), (() => { const v = visual?.states.find((x) => x.name === s.name); return v ? `${v.percent}%` : ''; })()])),
];
for (const s of inv.states) {
  blocks.push(h(id(), 2, `${s.name}: ${s.what}`));
  for (const [who, label] of [['oracle', 'Oracle (trial site)'], ['ours', 'Ours']]) {
    const file = `${shots}/${s.name}-${who}.png`;
    if (existsSync(file)) blocks.push(fig(id(), await upload(file), `${label}, ${s.what}`, label));
  }
  const v = visual?.states.find((x) => x.name === s.name);
  const tri = `${shots}/${s.name}-triptych.png`;
  if (v && existsSync(tri)) blocks.push(fig(id(), await upload(tri), `Oracle, ours and the pixels that differ, ${s.what}`, `Canvas only: oracle, ours, and in red the ${v.percent}% of pixels that differ`));
  const rows = s.missing.filter((m) => m.status !== 'tracked').sort((a, b) => ORDER.indexOf(a.status) - ORDER.indexOf(b.status)).map((m) => [m.label, m.status, [...m.items, ...m.outOfScope].join(', ') || '']);
  if (rows.length) blocks.push(table(id(), ['Missing in ours', 'Status', 'Items'], rows));
  blocks.push(p(id(), `${s.present} of ${s.oracle} oracle labels are also on our canvas; ${n(s, 'tracked')} missing ones are tracked by an item.${s.error ? ` This state did not run cleanly: ${s.error}` : ''}`));
}
const payload = { title: `Fluid editor gap review ${inv.capturedAt}`, blocks };
const file = `${shots}/review-payload.json`;
writeFileSync(file, JSON.stringify(payload, null, 2));
execFileSync('bp', ['bulldocs', 'publish', slug, '--file', file, '--yes'], { stdio: 'inherit' });
console.log(`${server}/papers/${slug}`);
